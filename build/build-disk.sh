#!/usr/bin/env bash
# build-disk.sh — Build a bootable GPT disk image for Rogue Linux
#
# Layout:
#   Partition 1 : EFI System Partition  (FAT32, 64 MB)
#   Partition 2 : Root filesystem       (ext4, rest of disk)
#
# Requires: sgdisk, mkfs.fat, mkfs.ext4, grub-install (x86_64-efi),
#           losetup, mount — all need sudo.
#
# Usage: sudo bash build-disk.sh [SIZE_MB]   (default 1024)

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ROOTFS="$ROOT/rootfs"
IMG="$ROOT/build/rogue-linux-disk.img"
SIZE_MB="${1:-1024}"
KERNEL="$ROOTFS/boot/vmlinuz-6.6.75"
MNT_ROOT="/tmp/rogue-mnt-root"
MNT_EFI="/tmp/rogue-mnt-root/boot/efi"

# ── preflight ────────────────────────────────────────────────────────────
[ "$(id -u)" = "0" ] || { echo "ERROR: run with sudo"; exit 1; }
[ -f "$KERNEL" ] || { echo "ERROR: kernel not found at $KERNEL"; exit 1; }
for cmd in sgdisk mkfs.fat mkfs.ext4 grub-install losetup; do
    command -v $cmd >/dev/null || { echo "ERROR: $cmd not found"; exit 1; }
done

# ── clean up any previous state ──────────────────────────────────────────
if losetup -a | grep -q "rogue-linux-disk.img"; then
    OLD=$(losetup -a | grep "rogue-linux-disk.img" | cut -d: -f1)
    umount "$MNT_EFI"   2>/dev/null || true
    umount "$MNT_ROOT"  2>/dev/null || true
    losetup -d "$OLD"   2>/dev/null || true
fi
rm -f "$IMG"
rm -rf "$MNT_ROOT"

echo ""
echo "╔══════════════════════════════════════════╗"
echo "║   Rogue Linux — Disk Image Builder       ║"
echo "╚══════════════════════════════════════════╝"
echo ""

# ── step 1: raw image ────────────────────────────────────────────────────
echo "[1/7] Creating ${SIZE_MB}MB raw disk image..."
dd if=/dev/zero of="$IMG" bs=1M count="$SIZE_MB" status=none
echo "  image : $IMG"

# ── step 2: GPT partition table ──────────────────────────────────────────
echo "[2/7] Partitioning (GPT: ESP 64MB + ext4 root)..."
sgdisk -Z "$IMG"                                         >/dev/null
sgdisk -n 1:0:+64M   -t 1:ef00 -c 1:"EFI System"   "$IMG" >/dev/null
sgdisk -n 2:0:0      -t 2:8300 -c 2:"Rogue Linux"   "$IMG" >/dev/null
echo "  GPT written"

# ── step 3: loop device ──────────────────────────────────────────────────
echo "[3/7] Attaching loop device..."
LOOP=$(losetup -f --show -P "$IMG")
echo "  loop  : $LOOP  (${LOOP}p1=ESP  ${LOOP}p2=root)"
# Give udev a moment to create partition nodes
sleep 1
[ -b "${LOOP}p1" ] || { partprobe "$LOOP" 2>/dev/null; sleep 1; }

# ── step 4: format ───────────────────────────────────────────────────────
echo "[4/7] Formatting partitions..."
mkfs.fat -F32 -n "ROGUEBOOT" "${LOOP}p1" >/dev/null
mkfs.ext4 -q -L "rogue-linux" "${LOOP}p2"
ROOT_UUID=$(blkid -s UUID -o value "${LOOP}p2")
echo "  ESP   : FAT32"
echo "  root  : ext4  UUID=$ROOT_UUID"

# ── step 5: mount and populate ───────────────────────────────────────────
echo "[5/7] Copying rootfs to disk..."
mkdir -p "$MNT_ROOT"
mount "${LOOP}p2" "$MNT_ROOT"
mkdir -p "$MNT_EFI"
mount "${LOOP}p1" "$MNT_EFI"

cp -a "$ROOTFS/." "$MNT_ROOT/"

# Update /etc/fstab with real UUIDs
ESP_UUID=$(blkid -s UUID -o value "${LOOP}p1")
cat > "$MNT_ROOT/etc/fstab" << FSTAB
# /etc/fstab — generated by build-disk.sh
UUID=$ROOT_UUID  /         ext4  defaults,noatime    0  1
UUID=$ESP_UUID   /boot/efi vfat  umask=0077          0  2
proc             /proc     proc  defaults             0  0
sysfs            /sys      sysfs defaults             0  0
devtmpfs         /dev      devtmpfs defaults          0  0
tmpfs            /tmp      tmpfs defaults,nosuid      0  0
tmpfs            /run      tmpfs defaults,nosuid,mode=0755  0  0
FSTAB

mkdir -p "$MNT_ROOT/boot/efi"
echo "  copied : $(du -sh "$MNT_ROOT" | cut -f1) total"

# ── step 6: GRUB EFI ─────────────────────────────────────────────────────
echo "[6/7] Installing GRUB (x86_64-efi, removable)..."
grub-install \
    --target=x86_64-efi \
    --efi-directory="$MNT_EFI" \
    --boot-directory="$MNT_ROOT/boot" \
    --removable \
    --no-nvram \
    2>/dev/null

mkdir -p "$MNT_ROOT/boot/grub"

# Copy initramfs onto the disk if one was already built
INITRD_SRC="$ROOT/build/rogue-linux.cpio.gz"
INITRD_DISK="$MNT_ROOT/boot/initramfs.cpio.gz"
INITRD_GRUB_LINE=""
if [ -f "$INITRD_SRC" ]; then
    cp "$INITRD_SRC" "$INITRD_DISK"
    INITRD_GRUB_LINE="    initrd /boot/initramfs.cpio.gz"
    echo "  initrd : copied to /boot/initramfs.cpio.gz"
else
    echo "  initrd : not found — GRUB will boot without initramfs"
fi

cat > "$MNT_ROOT/boot/grub/grub.cfg" << GRUBCFG
# Rogue Linux — GRUB configuration
# Generated by build-disk.sh

set default=0
set timeout=3
set timeout_style=countdown

insmod part_gpt
insmod ext2
insmod fat

# Primary entry: initramfs pivot_root path (if initramfs present)
# Falls back to direct disk mount if no initrd line below.
menuentry "Rogue Linux (cogman init)" {
    search --no-floppy --fs-uuid --set=root $ROOT_UUID
    linux  /boot/vmlinuz-6.6.75 \\
           root=UUID=$ROOT_UUID rw \\
           init=/init \\
           console=ttyS0 \\
           -- --services-dir /etc/cogman/services
${INITRD_GRUB_LINE}
    echo "Booting Rogue Linux..."
}

menuentry "Rogue Linux (single user)" {
    search --no-floppy --fs-uuid --set=root $ROOT_UUID
    linux  /boot/vmlinuz-6.6.75 \\
           root=UUID=$ROOT_UUID rw \\
           init=/bin/sh \\
           console=ttyS0
}
GRUBCFG

echo "  GRUB EFI installed"
echo "  grub.cfg root=UUID=$ROOT_UUID"

# ── step 7: unmount ──────────────────────────────────────────────────────
echo "[7/7] Unmounting..."
sync
umount "$MNT_EFI"
umount "$MNT_ROOT"
losetup -d "$LOOP"
rm -rf "$MNT_ROOT"

echo ""
echo "DISK BUILD OK"
echo "  image  : $IMG  ($(du -h "$IMG" | cut -f1))"
echo "  root   : UUID=$ROOT_UUID"
echo ""
echo "  Boot (UEFI GRUB):   sudo bash $ROOT/build/boot-disk.sh"
echo "  Boot (direct/fast): bash $ROOT/build/boot-disk-direct.sh"
